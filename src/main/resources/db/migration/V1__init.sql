CREATE TABLE asset (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    type        VARCHAR(32)  NOT NULL,
    criticality VARCHAR(16)  NOT NULL,
    owner       VARCHAR(255),
    created_at  TIMESTAMP WITH TIME ZONE    NOT NULL,
    CONSTRAINT uq_asset_name UNIQUE (name)
);

CREATE TABLE scan (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tool          VARCHAR(16)  NOT NULL,
    source_file   VARCHAR(255),
    imported_at   TIMESTAMP WITH TIME ZONE    NOT NULL,
    total_count   INT          NOT NULL,
    new_count     INT          NOT NULL,
    reopened_count INT         NOT NULL,
    resolved_count INT         NOT NULL
);

CREATE TABLE finding (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fingerprint      VARCHAR(64)   NOT NULL,
    asset_id         BIGINT        NOT NULL REFERENCES asset (id),
    tool             VARCHAR(16)   NOT NULL,
    title            VARCHAR(500)  NOT NULL,
    description      VARCHAR(4000),
    remediation      VARCHAR(2000),
    severity         VARCHAR(16)   NOT NULL,
    cvss             DOUBLE PRECISION,
    cve_id           VARCHAR(32),
    cwe_id           VARCHAR(32),
    epss             DOUBLE PRECISION,
    epss_updated_at  TIMESTAMP WITH TIME ZONE,
    known_exploited  BOOLEAN       NOT NULL DEFAULT FALSE,
    location         VARCHAR(1000),
    component        VARCHAR(255),
    installed_version VARCHAR(100),
    fixed_version    VARCHAR(100),
    status           VARCHAR(20)   NOT NULL,
    priority_score   DOUBLE PRECISION NOT NULL DEFAULT 0,
    assignee         VARCHAR(255),
    first_seen       TIMESTAMP WITH TIME ZONE     NOT NULL,
    last_seen        TIMESTAMP WITH TIME ZONE     NOT NULL,
    due_date         TIMESTAMP WITH TIME ZONE     NOT NULL,
    resolved_at      TIMESTAMP WITH TIME ZONE,
    last_scan_id     BIGINT REFERENCES scan (id),
    CONSTRAINT uq_finding_fingerprint UNIQUE (fingerprint)
);

CREATE INDEX idx_finding_status   ON finding (status);
CREATE INDEX idx_finding_severity ON finding (severity);
CREATE INDEX idx_finding_asset    ON finding (asset_id);
CREATE INDEX idx_finding_cve      ON finding (cve_id);
CREATE INDEX idx_finding_priority ON finding (priority_score);

CREATE TABLE finding_event (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    finding_id  BIGINT       NOT NULL REFERENCES finding (id) ON DELETE CASCADE,
    type        VARCHAR(24)  NOT NULL,
    from_status VARCHAR(20),
    to_status   VARCHAR(20),
    note        VARCHAR(2000),
    actor       VARCHAR(255),
    created_at  TIMESTAMP WITH TIME ZONE    NOT NULL
);

CREATE INDEX idx_event_finding ON finding_event (finding_id);
